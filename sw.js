// BookVault PWA: cache only local app shell. Never cache payments, private PDFs or Firebase data.
const CACHE_NAME = 'bookvault-shell-v1';
const SHELL = ['./', './index.html', './manifest.webmanifest', './icons/icon-192.png', './icons/icon-512.png'];
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE_NAME).then(cache => cache.addAll(SHELL)));
  self.skipWaiting();
});
self.addEventListener('activate', event => {
  event.waitUntil(Promise.all([
    caches.keys().then(keys => Promise.all(keys.filter(key => key !== CACHE_NAME).map(key => caches.delete(key)))),
    self.clients.claim()
  ]));
});
self.addEventListener('fetch', event => {
  const request = event.request;
  if (request.method !== 'GET') return;
  const url = new URL(request.url);
  if (url.origin !== self.location.origin) return;
  if (request.mode === 'navigate') {
    event.respondWith(fetch(request).catch(() => caches.match('./index.html')));
    return;
  }
  const shellPath = ['/manifest.webmanifest', '/icons/icon-192.png', '/icons/icon-512.png'];
  if (shellPath.some(path => url.pathname.endsWith(path))) {
    event.respondWith(caches.match(request).then(hit => hit || fetch(request)));
  }
});
